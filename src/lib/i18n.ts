export type Lang = 'id' | 'en';

/**
 * Translation.
 *
 * A dictionary and a lookup, rather than a library. The app has one namespace,
 * no plural rules beyond a count word, and nothing worth lazy loading: both
 * languages together are a few kilobytes, so shipping them in the bundle means
 * switching is instant with nothing to fetch.
 *
 * Indonesian is the default. English is the fallback for any key that has not
 * been translated, so a gap degrades to readable English rather than to a raw
 * key on screen.
 */

export const LANGUAGES: { id: Lang; label: string; short: string }[] = [
  { id: 'id', label: 'Bahasa Indonesia', short: 'ID' },
  { id: 'en', label: 'English', short: 'EN' },
];

export const DEFAULT_LANG: Lang = 'id';

export function isLang(v: unknown): v is Lang {
  return v === 'id' || v === 'en';
}

/** Locale for Intl, so dates and numbers follow the chosen language. */
export function localeFor(lang: Lang): string {
  return lang === 'id' ? 'id-ID' : 'en-US';
}

type Vars = Record<string, string | number>;

/** Fills {name} placeholders. A missing value is left visible, not blanked. */
function fill(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, key) =>
    key in vars ? String(vars[key]) : whole,
  );
}

export function translate(lang: Lang, key: string, vars?: Vars): string {
  const table = lang === 'id' ? ID : EN;
  const value = table[key] ?? EN[key];
  if (value === undefined) return key;
  return fill(value, vars);
}

